// Bundle KaTeX fonts locally: formulas must work offline in native WebViews.
const fs = require('node:fs');
const path = require('node:path');
const root = path.dirname(require.resolve('katex/package.json'));
let css = fs.readFileSync(path.join(root, 'dist/katex.min.css'), 'utf8');
css = css.replace(/src:([^}]+?)(?=;|})/g, (all, sources) => {
  const font = sources.match(/url\((?:["'])?(fonts\/[^)"']+\.woff2)(?:["'])?\)/);
  if (!font) throw new Error('Missing WOFF2 font');
  return `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(root, 'dist', font[1])).toString('base64')}) format("woff2")`;
});
const dest = path.join(__dirname, '../src/components/chat');
fs.writeFileSync(path.join(dest, 'katexStyles.generated.ts'), '// Generated by scripts/build-math-assets.cjs. See KaTeX-LICENSE.txt.\nexport default ' + JSON.stringify(css) + ';\n');
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(dest, 'KaTeX-LICENSE.txt'));
